namespace slskd.Shares
{
    using System;
    using System.Collections.Generic;

    /// <summary>
    ///     A directory discovered during a share scan, along with the files found directly within it.
    /// </summary>
    /// <param name="Name">The masked (remote) name of the directory.</param>
    /// <param name="Files">The files found directly within the directory.</param>
    public sealed record ScannedDirectory(string Name, IReadOnlyList<ScannedFile> Files);

    /// <summary>
    ///     A file discovered during a share scan.
    /// </summary>
    /// <param name="OriginalFilename">The fully qualified local path of the file.</param>
    /// <param name="TouchedAt">The timestamp at which the file was last modified, according to the host OS.</param>
    /// <param name="File">The file, whose filename is the masked (remote) path.</param>
    public readonly record struct ScannedFile(string OriginalFilename, DateTime TouchedAt, Soulseek.File File);
}
