namespace slskd.Users.API
{
    /// <summary>
    ///     A request for the files in a directory from a cached browse response.
    /// </summary>
    public class BrowseFilesRequest
    {
        /// <summary>
        ///     The default maximum number of files to return.
        /// </summary>
        public const int DefaultLimit = 5001;

        /// <summary>
        ///     The largest allowed maximum number of files to return.
        /// </summary>
        public const int MaxLimit = 100_000;

        /// <summary>
        ///     Gets or sets the exact name of the directory.
        /// </summary>
        public string Directory { get; set; }

        /// <summary>
        ///     Gets or sets a value indicating whether the files in descendant directories should be included.
        /// </summary>
        public bool Recursive { get; set; }

        /// <summary>
        ///     Gets or sets the maximum number of files to return. Clamped to 1..<see cref="MaxLimit"/>.
        /// </summary>
        public int Limit { get; set; } = DefaultLimit;
    }
}
