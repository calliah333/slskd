namespace slskd.Users.API
{
    using System.Collections.Generic;

    /// <summary>
    ///     The files in a directory, and optionally its descendants, from a cached browse response.
    /// </summary>
    public record BrowseFilesResponse
    {
        /// <summary>
        ///     Gets the number of files in the matched directories, regardless of the limit.
        /// </summary>
        public int Total { get; init; }

        /// <summary>
        ///     Gets a value indicating whether files were omitted because of the limit.
        /// </summary>
        public bool Truncated { get; init; }

        /// <summary>
        ///     Gets the matched directories; the requested directory first, then descendants, in the order they were received.
        /// </summary>
        public IEnumerable<BrowseDirectoryFilesResponse> Directories { get; init; }
    }
}
