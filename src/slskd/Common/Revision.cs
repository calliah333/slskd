namespace slskd
{
    using System;
    using System.Threading;

    /// <summary>
    ///     Issues revision numbers that identify a version of some mutable messaging state (a room's messages, a
    ///     conversation, etc.) so that clients can cheaply ask whether anything changed since their last read.
    /// </summary>
    /// <remarks>
    ///     Revisions are drawn from a single process-wide sequence seeded with the current time, so a revision is never
    ///     reused: not for a different room or conversation, and not after a restart.
    /// </remarks>
    public static class Revision
    {
        private static long Last = DateTime.UtcNow.Ticks;

        /// <summary>
        ///     Returns a new, unique revision.
        /// </summary>
        /// <returns>The new revision.</returns>
        public static long Next() => Interlocked.Increment(ref Last);
    }
}
