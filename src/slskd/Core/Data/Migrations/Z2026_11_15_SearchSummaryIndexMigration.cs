namespace slskd.Migrations;

using System;
using System.Linq;
using Microsoft.Data.Sqlite;
using Serilog;

/// <summary>
///     Adds a covering index to the Searches table for every query that omits responses (the search list, lookups, and
///     pruning), so that SQLite doesn't have to walk the overflow pages of each search's ResponsesJson to reach the columns
///     stored after it.
/// </summary>
public class Z2026_11_15_SearchSummaryIndexMigration : IMigration
{
    public Z2026_11_15_SearchSummaryIndexMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.Search];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext<Z2026_11_15_SearchSummaryIndexMigration>();
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        var idxes = SchemaInspector.GetDatabaseIndexes(ConnectionString);

        if (!idxes.TryGetValue("Searches", out var searches))
        {
            // the table is created (with the index) from the EF model; nothing to migrate
            return false;
        }

        return !searches.Any(c => c.Name.Equals("IDX_Searches_Summary", StringComparison.OrdinalIgnoreCase));
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_11_15_SearchSummaryIndexMigration));
            return;
        }

        using var connection = new SqliteConnection(ConnectionString);
        connection.Open();

        using var transaction = connection.BeginTransaction();

        try
        {
            Log.Information("> Adding missing index on the Searches table...");

            using var command = new SqliteCommand(
                "CREATE INDEX IF NOT EXISTS IDX_Searches_Summary ON Searches (Id, StartedAt, EndedAt, FileCount, LockedFileCount, ResponseCount, SearchText, State, Token)",
                connection,
                transaction);

            command.ExecuteNonQuery();

            Log.Information("> Index created");
            transaction.Commit();
            Log.Information("> Done!");
        }
        catch (Exception)
        {
            transaction.Rollback();
            throw;
        }
    }
}
